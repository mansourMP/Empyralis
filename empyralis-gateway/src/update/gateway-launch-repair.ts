import { promises as fsp } from "fs";
import path from "path";

import { execFileWithTimeout } from "../shell/exec-file-with-timeout";
import { currentReleaseEntrypoint } from "./gateway-launch-path";
import { resolveGatewayReleaseLayout } from "./gateway-release-layout";

/**
 * THE HALF OF THE REPAIR A GATEWAY IS ALLOWED TO DO.
 *
 * gateway-launch-updatability.ts establishes, with measurements from
 * production rather than reasoning, that a gateway cannot rewrite its own
 * systemd unit: it runs as an unprivileged user, `/` is mounted read-only
 * inside its own mount namespace (ProtectSystem=strict), NoNewPrivileges
 * forbids escalation, and `daemon-reload` needs root regardless. So one line
 * of the repair belongs to a human, permanently.
 *
 * Everything ELSE belongs here. The gateway writes, into the one directory it
 * genuinely owns (its own state dir, already in the unit's ReadWritePaths), a
 * launcher that resolves the release layout at every start — so the human's
 * remaining action shrinks to a single `ExecStart=` line, applied once, that
 * never has to be revisited again as builds change.
 *
 * WHY A LAUNCHER RATHER THAN THE ENTRYPOINT ITSELF. The obvious instruction —
 * point ExecStart at `<installRoot>/current/gateway/dist/index.js` — is a
 * loaded gun on a machine nobody can reach: on a box that has never
 * self-updated that path does not exist, so the very first `systemctl
 * restart` after the edit fails and the box is gone, permanently, with no way
 * in. This launcher cannot do that. It prefers the layout when a release is
 * actually staged there and otherwise execs THE EXACT PATH THIS PROCESS IS
 * RUNNING FROM RIGHT NOW — a path proven to work at the instant the file was
 * written, because it is the one currently working. Worst case after the
 * operator's edit is a box that behaves precisely as it does today.
 *
 * WHY IT IS PROBED BEFORE BEING RECOMMENDED. Handing an operator an
 * `ExecStart=` pointing at a script that turns out to be non-executable, on a
 * `noexec` mount, or without a usable `/bin/sh`, converts a stale box into a
 * dead one. So the launcher is RUN once, here, in probe mode (it prints the
 * entrypoint it would exec and exits 0 without starting anything), and the
 * repair instruction is only reported as ready when that probe actually
 * succeeded. An unproven launcher is never advertised.
 */

/** Set by the probe below. The launcher prints what it WOULD start and exits
 *  without starting it — so verification never spawns a second gateway (the
 *  process lock would make that harmless, but "harmless" is not a reason to
 *  do it). */
export const GATEWAY_LAUNCH_PROBE_ENV = "EMPYRALIS_GATEWAY_LAUNCH_PROBE";

const PROBE_TIMEOUT_MS = 5_000;

export interface GatewayLaunchRepairPlan {
  /** Absolute path of the launcher this gateway wrote and verified. */
  launcherPath: string;
  /** Verbatim line an operator puts in the unit. */
  execStartLine: string;
  /** Proven by actually running the launcher, never assumed. */
  verified: boolean;
  /** Why verification failed, when it did — a repair that cannot be proven
   *  is reported as unusable rather than quietly recommended. */
  failureReason: string | null;
}

/** POSIX single-quoting: everything is literal inside '…', and an embedded
 *  quote is closed, escaped and reopened. Applied to every interpolated path
 *  so a directory containing a quote or a space cannot produce a script that
 *  execs something else. */
export function shellSingleQuote(value: string): string {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

/**
 * `/bin/sh`, not bash: a minimal cloud image is not guaranteed to have bash,
 * and this file's whole job is to be the thing that still works.
 */
export function renderGatewayLaunchScript(params: {
  layoutEntrypoint: string;
  fallbackEntrypoint: string;
  nodePath: string;
}): string {
  return `#!/bin/sh
# Generated by the Empyralis gateway. Do not edit — it is rewritten on every
# start, and it deliberately holds no policy of its own.
#
# Prefers the build a self-update staged; falls back to the exact entrypoint
# the gateway was running from when this file was written, so a box whose
# update folder is still empty starts exactly what it starts today.
set -eu

CANDIDATE=${shellSingleQuote(params.layoutEntrypoint)}
FALLBACK=${shellSingleQuote(params.fallbackEntrypoint)}
NODE=${shellSingleQuote(params.nodePath)}

if [ -f "$CANDIDATE" ]; then
  entry="$CANDIDATE"
else
  entry="$FALLBACK"
fi

if [ "\${${GATEWAY_LAUNCH_PROBE_ENV}:-}" = "1" ]; then
  printf '%s\\n' "$entry"
  exit 0
fi

cd "$(dirname "$entry")"
exec "$NODE" "$entry"
`;
}

export interface EnsureGatewayLaunchRepairOptions {
  stateDir: string;
  /** The path this process is actually running from — the fallback, and the
   *  only entrypoint known to work at this instant. */
  runningEntryPath: string;
  nodePath?: string;
  env?: NodeJS.ProcessEnv;
  /** Injectable for tests; production writes with fsp. */
  writeFile?: (filePath: string, contents: string, mode: number) => Promise<void>;
  mkdir?: (dirPath: string) => Promise<void>;
  /** Injectable probe. Returns the entrypoint the launcher reported, or
   *  throws. */
  probe?: (launcherPath: string) => Promise<string>;
}

async function defaultProbe(launcherPath: string): Promise<string> {
  const result = await execFileWithTimeout(
    launcherPath,
    [],
    PROBE_TIMEOUT_MS,
    { env: { ...process.env, [GATEWAY_LAUNCH_PROBE_ENV]: "1" } },
  );
  if (result.error) {
    throw result.error;
  }
  if (result.timedOut) {
    throw new Error("the launcher did not answer in time");
  }
  if (result.exitCode !== 0) {
    throw new Error(
      `the launcher exited with code ${result.exitCode}${result.stderr ? `: ${result.stderr.trim()}` : ""}`,
    );
  }
  return result.stdout.trim();
}

/**
 * Write and PROVE the launcher, returning the one line an operator has to
 * apply. Never throws; a failure comes back as `verified: false` with the
 * reason, because a gateway that cannot prepare its own repair must still
 * run and must still say so.
 */
export async function ensureGatewayLaunchRepair(
  opts: EnsureGatewayLaunchRepairOptions,
): Promise<GatewayLaunchRepairPlan | null> {
  const stateDir = String(opts.stateDir || "").trim();
  const runningEntryPath = String(opts.runningEntryPath || "").trim();
  if (!stateDir || !runningEntryPath) {
    return null;
  }
  const env = opts.env ?? process.env;
  const nodePath = String(opts.nodePath || "").trim() || process.execPath;
  const launcherDir = path.join(stateDir, "launch");
  const launcherPath = path.join(launcherDir, "run-gateway");
  const execStartLine = `ExecStart=${launcherPath}`;

  const layout = resolveGatewayReleaseLayout({ stateDir, env });
  const contents = renderGatewayLaunchScript({
    layoutEntrypoint: currentReleaseEntrypoint(layout),
    fallbackEntrypoint: runningEntryPath,
    nodePath,
  });

  const mkdir =
    opts.mkdir ?? (async (dirPath: string) => {
      await fsp.mkdir(dirPath, { recursive: true, mode: 0o700 });
    });
  const writeFile =
    opts.writeFile ?? (async (filePath: string, body: string, mode: number) => {
      await fsp.writeFile(filePath, body, { mode });
      // writeFile's `mode` only applies when it CREATES the file, so an
      // existing launcher whose exec bit was stripped would stay unusable —
      // exactly the state that turns this repair into an unbootable box.
      await fsp.chmod(filePath, mode);
    });

  try {
    await mkdir(launcherDir);
    await writeFile(launcherPath, contents, 0o700);
  } catch (error) {
    return {
      launcherPath,
      execStartLine,
      verified: false,
      failureReason: `could not write the launcher — ${error instanceof Error ? error.message : String(error)}`,
    };
  }

  const probe = opts.probe ?? defaultProbe;
  try {
    const reported = await probe(launcherPath);
    if (!reported) {
      return {
        launcherPath,
        execStartLine,
        verified: false,
        failureReason: "the launcher did not report which build it would start",
      };
    }
    return { launcherPath, execStartLine, verified: true, failureReason: null };
  } catch (error) {
    return {
      launcherPath,
      execStartLine,
      verified: false,
      failureReason: `the launcher could not be run — ${error instanceof Error ? error.message : String(error)}`,
    };
  }
}
