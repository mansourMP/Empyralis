test("launchd: a per-user domain miss falls through to the system domain", async () => {
  const printOutput = `system/ai.empyralis.agent-computer = {
\tpath = /Library/LaunchDaemons/ai.empyralis.agent-computer.plist
\tprogram = /usr/local/bin/node
\targuments = {
\t\t/usr/local/bin/node
\t\t/Users/someone/checkout/empyralis-gateway/dist/index.js
\t}
\tproperties = keepalive | runatload
}
`;
  const asked: string[] = [];
  const result = await classifyGatewayLaunchUpdatability({
    env: { EMPYRALIS_LAUNCHD_LABEL: "ai.empyralis.agent-computer" },
    platform: "darwin",
    homeDir: "/Users/someone",
    uid: 501,
    stateDir: "/Users/someone/.empyralis/gateway",
    readFile: readerFor({}),
    runCommand: async (_command, args) => {
      asked.push(args[1]);
      if (args[1].startsWith("gui/")) {
        return { exitCode: 113, stdout: "", stderr: "Could not find service", timedOut: false };
      }
      return { exitCode: 0, stdout: printOutput, stderr: "", timedOut: false };
    },
  });

  assert.deepEqual(asked, [
    "gui/501/ai.empyralis.agent-computer",
    "system/ai.empyralis.agent-computer",
  ]);
  assert.equal(result.configSource, "launchd-effective");
  // The path is genuinely outside the layout — that blocker is real. The
  // KeepAlive one is not, because the loaded job reports keepalive.
  assert.deepEqual(
    result.blockers.map((blocker) => blocker.code),
    [LAUNCH_CODE_PATH_OUTSIDE_LAYOUT],
  );
});

test("parsers: the shapes systemd and launchd actually produce", () => {
  assert.equal(
    parseSystemdUnitFromCgroup("0::/system.slice/empyralis-gateway-channels.service\n"),
    "empyralis-gateway-channels.service",
  );
  assert.equal(parseSystemdUnitFromCgroup("0::/user.slice/session-3.scope\n"), null);

  // systemd's own ExecStart prefixes must not leak into the command.
  assert.equal(parseSystemdExecStart("[Service]\nExecStart=-/usr/bin/node /a.js"), "/usr/bin/node /a.js");
  assert.equal(parseSystemdExecStart("[Service]\nExecStart=+/usr/bin/node /a.js"), "/usr/bin/node /a.js");
  assert.equal(
    parseSystemdExecStart("[Service]\nExecStart=/usr/bin/node \\\n  /a.js"),
    "/usr/bin/node /a.js",
  );
  assert.equal(parseSystemdExecStart("[Service]\nRestart=always"), null);

  // Last assignment wins, matching systemd's own parsing.
  assert.equal(parseSystemdRestartPolicy("Restart=no\nRestart=always"), "always");
  assert.equal(parseSystemdRestartPolicy("[Service]\nType=simple"), null);

  assert.deepEqual(
    parseLaunchdProgramArguments(
      "<key>ProgramArguments</key><array><string>/bin/node</string><string>/a.js</string></array>",
    ),
    ["/bin/node", "/a.js"],
  );
  assert.deepEqual(parseLaunchdProgramArguments("<plist></plist>"), []);
  assert.equal(parseLaunchdKeepAlive("<key>KeepAlive</key><true/>"), true);
  assert.equal(parseLaunchdKeepAlive("<key>KeepAlive</key><false/>"), false);
  // A KeepAlive DICT is conditional, so it is not a promise that a
  // deliberate exit comes back.
  assert.equal(
    parseLaunchdKeepAlive("<key>KeepAlive</key><dict><key>Crashed</key><true/></dict>"),
    false,
  );
});

test("parsers: `systemctl show`'s structured ExecStart, read off production", () => {
  const properties = parseSystemctlShowProperties(
    systemctlShowOutput({
      program: "/var/lib/empyralis-gw/state/launch/run-gateway",
      argv: "/var/lib/empyralis-gw/state/launch/run-gateway",
      restart: "always",
      dropIns: ["/etc/systemd/system/x.service.d/a.conf", "/etc/systemd/system/x.service.d/b.conf"],
    }),
  );
  assert.deepEqual(properties.get("Restart"), ["always"]);
  assert.equal(properties.get("ExecStart")?.length, 1);

  // argv[] wins, and the ` ; `-separated runtime status after it is dropped.
  assert.equal(
    parseSystemdExecStartProperty(properties.get("ExecStart")![0]),
    "/var/lib/empyralis-gw/state/launch/run-gateway",
  );
  assert.equal(
    parseSystemdExecStartProperty(
      "{ path=/usr/bin/node ; argv[]=/usr/bin/node /a.js ; ignore_errors=no ; pid=1 }",
    ),
    "/usr/bin/node /a.js",
  );
  // path= is the fallback when a shape carries no argv.
  assert.equal(
    parseSystemdExecStartProperty("{ path=/usr/bin/node ; ignore_errors=no }"),
    "/usr/bin/node",
  );
  // An unstructured value (an older systemd) is still an answer.
  assert.equal(parseSystemdExecStartProperty("/usr/bin/node /a.js"), "/usr/bin/node /a.js");
  assert.equal(parseSystemdExecStartProperty(""), null);

  // A repeated key keeps every value, in order — a unit may declare several.
  const repeated = parseSystemctlShowProperties("ExecStart=a\nExecStart=b\nRestart=always\n");
  assert.deepEqual(repeated.get("ExecStart"), ["a", "b"]);

  // A path containing '=' survives: only the FIRST '=' separates key from value.
  const oddValue = parseSystemctlShowProperties("FragmentPath=/etc/systemd/system/a=b.service\n");
  assert.deepEqual(oddValue.get("FragmentPath"), ["/etc/systemd/system/a=b.service"]);
});

test("parsers: `launchctl print`'s own shape", () => {
  const output = `gui/501/x = {
\tpath = /Users/x/Library/LaunchAgents/x.plist
\tprogram = /usr/local/bin/node
\targuments = {
\t\t/usr/local/bin/node
\t\t/opt/a.js
\t}
\tproperties = keepalive | runatload | system service
}
`;
  assert.equal(parseLaunchctlPrintCommand(output), "/usr/local/bin/node /opt/a.js");
  assert.equal(parseLaunchctlPrintPlistPath(output), "/Users/x/Library/LaunchAgents/x.plist");
  assert.equal(parseLaunchctlPrintKeepAlive(output), true);

  // `program` alone is the shape for a job declared without an argv, and is
  // the only fallback — never a guess.
  assert.equal(
    parseLaunchctlPrintCommand("gui/501/x = {\n\tprogram = /usr/local/bin/foo\n}\n"),
    "/usr/local/bin/foo",
  );
  assert.equal(parseLaunchctlPrintCommand("gui/501/x = {\n}\n"), null);

  // The keepalive token is POSITIVE-ONLY: its absence must not be read as a
  // promise that the job will not come back, or a healthy Mac gets a blocker
  // manufactured for it out of a token Apple never documented.
  assert.equal(
    parseLaunchctlPrintKeepAlive("gui/501/x = {\n\tproperties = runatload | system service\n}\n"),
    false,
  );
  assert.equal(parseLaunchctlPrintKeepAlive("gui/501/x = {\n}\n"), false);
  // The per-endpoint `keepalive = 0` lines launchctl prints inside its
  // endpoint blocks are NOT the job's KeepAlive and must not be read as it.
  assert.equal(
    parseLaunchctlPrintKeepAlive(
      "gui/501/x = {\n\tendpoints = {\n\t\t\"y\" = {\n\t\t\tkeepalive = 0\n\t\t}\n\t}\n}\n",
    ),
    false,
  );
});

