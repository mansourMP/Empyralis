function readerFor(files: Record<string, string>) {
  return async (filePath: string): Promise<string> => {
    if (filePath in files) {
      return files[filePath];
    }
    const error = new Error(`ENOENT: ${filePath}`) as NodeJS.ErrnoException;
    error.code = "ENOENT";
    throw error;
  };
}

/** systemd 255's own rendering, verbatim in shape: one structured ExecStart
 *  carrying runtime status fields that must NOT leak into the command. */
function systemctlShowOutput(params: {
  program: string;
  argv: string;
  restart: string;
  fragmentPath?: string;
  dropIns?: string[];
}): string {
  return [
    `Restart=${params.restart}`,
    `ExecStart={ path=${params.program} ; argv[]=${params.argv} ; ignore_errors=no ; ` +
      "start_time=[Tue 2026-08-18 11:29:57 UTC] ; stop_time=[n/a] ; pid=2338249 ; " +
      "code=(null) ; status=0/0 }",
    `FragmentPath=${params.fragmentPath ?? PRODUCTION_UNIT_PATH}`,
    `DropInPaths=${(params.dropIns ?? []).join(" ")}`,
    "",
  ].join("\n");
}

function systemctlRunner(stdout: string): GatewayLaunchCommandRunner {
  return async (command, args) => {
    assert.equal(command, "systemctl");
    assert.equal(args[0], "show");
    return { exitCode: 0, stdout, stderr: "", timedOut: false };
  };
}

/** No systemctl/launchctl on PATH: execFileWithTimeout reports the spawn
 *  failure, which the default runner turns into a null exit code. */
const unavailableRunner: GatewayLaunchCommandRunner = async () => ({
  exitCode: null,
  stdout: "",
  stderr: "",
  timedOut: false,
});

test("THE BUG: a drop-in repairs a stale base unit, and the box is reported updatable", async () => {
  // Exactly production after docs/DEPLOY-RUNBOOK.md's repair was applied:
  // the base file still says `/usr/bin/node /opt/…` + `Restart=on-failure`,
  // and `…service.d/empyralis-updatable.conf` overrides both. Reading the
  // file reported "not_updatable" at a box that was already fixed.
  const result = await classifyGatewayLaunchUpdatability({
    env: SYSTEMD_ENV,
    platform: "linux",
    stateDir: "/var/lib/empyralis-gw/state",
    readFile: readerFor({
      "/proc/self/cgroup": PRODUCTION_CGROUP,
      [PRODUCTION_UNIT_PATH]: PRODUCTION_UNIT,
      "/var/lib/empyralis-gw/state/launch/run-gateway": PRODUCTION_REPAIR_LAUNCHER,
    }),
    runCommand: systemctlRunner(
      systemctlShowOutput({
        program: "/var/lib/empyralis-gw/state/launch/run-gateway",
        argv: "/var/lib/empyralis-gw/state/launch/run-gateway",
        restart: "always",
        dropIns: [
          "/etc/systemd/system/empyralis-gateway-channels.service.d/empyralis-updatable.conf",
        ],
      }),
    ),
  });

  assert.equal(result.status, "updatable");
  assert.deepEqual(result.blockers, []);
  assert.equal(result.configSource, "systemd-effective");
  assert.equal(result.launchCommand, "/var/lib/empyralis-gw/state/launch/run-gateway");
  // The operator is shown the override that is actually in force, not just
  // the base file that disagrees with it.
  assert.deepEqual(result.overridePaths, [
    "/etc/systemd/system/empyralis-gateway-channels.service.d/empyralis-updatable.conf",
  ]);
  assert.equal(result.unknownReason, null);
});

